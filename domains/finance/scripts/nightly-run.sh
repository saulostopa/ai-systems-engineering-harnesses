#!/usr/bin/env bash
# nightly-run.sh — Finance Harness nightly pipeline (Lesson 13: autonomous loop).
# Queries the context, generates the report with sources and publishes — no human.
# Usage: ./nightly-run.sh <area_root> [--questions "question 1 | question 2"]
# Crontab:  0 3 * * * /caminho/domains/finance/scripts/nightly-run.sh /caminho/area_context >> /var/log/harness-finance.log 2>&1
set -uo pipefail

AREA_ROOT="${1:-}"
[ -d "$AREA_ROOT" ] || { echo "Usage: nightly-run.sh <area_root>"; exit 1; }

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PLAYBOOK="$(cd "$SCRIPT_DIR/.." && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../../../" && pwd)"
# Area Copilot engine: adds the packages to PYTHONPATH
export PYTHONPATH="${PYTHONPATH:-}:$REPO_ROOT/area-copilot:$REPO_ROOT/rag-harness"
DATE="$(date +%Y-%m-%d)"
OUT="$PLAYBOOK/relatorios/$DATE-resumo.md"
mkdir -p "$PLAYBOOK/relatorios"

DEFAULT_QUESTIONS="what are the totals of meta_vendas and veiculos_vendidos for the most recent month | are there missing data in the spreadsheets | was there divergence between expected and actual"
QUESTIONS="${HARNESS_QUESTIONS:-$DEFAULT_QUESTIONS}"

echo "== nightly-run: $(date -Iseconds)"
echo "== indexing context..."
python3 -m area_harness index "$AREA_ROOT" --verbose 2>/dev/null || {
  echo "ERROR: indexing failed (is area_copilot reachable? pip install -e area-copilot?)"
  exit 1
}

{
  echo "# Financial summary — $DATE"
  echo
  echo "Pipeline: domains/finance nightly-run.sh | Playbook OK: $([ -x "$PLAYBOOK/scripts/validate-playbook.sh" ] && "$PLAYBOOK/scripts/validate-playbook.sh" >/dev/null 2>&1 && echo yes || echo NO)"
  echo
  IFS='|' read -ra QS <<< "$QUESTIONS"
  for q in "${QS[@]}"; do
    q="$(echo "$q" | xargs)"
    echo "## $q"
    echo
    python3 -m area_harness query "$AREA_ROOT" "$q" 2>/dev/null || echo "No context for this question."
    echo
  done
  echo "_Generated by harness — sources cited in the body._"
} > "$OUT"

echo "== report: $OUT"

# Loop exit criterion (Lesson 09): every number is INSIDE a FONTE block.
# awk: tracks blocks that start with "FONTE:" and end at a blank line.
SEM_FONTE=$(awk '
  /FONTE:/ { in_fonte = 1; next }
  /^$/ { in_fonte = 0 }
  /meta_vendas|veiculos_vendidos/ && !in_fonte { bad++ }
  END { print bad + 0 }
' "$OUT")
FONTES=$(grep -c "FONTE:" "$OUT" || true)
if [ "$FONTES" -eq 0 ]; then
  echo "!! CRITERION FAILED: report with no FONTE cited — will not publish"
  exit 1
fi
if [ "$SEM_FONTE" -gt 0 ]; then
  echo "!! CRITERION FAILED: $SEM_FONTE excerpt(s) with a number outside a FONTE block — will not publish"
  exit 1
fi
echo "== published: OK ($FONTES sources cited)"